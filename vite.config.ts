import { defineConfig, type Plugin } from "vite";
import tailwindcss from "@tailwindcss/vite";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve, join } from "node:path";

// heartbank.org — a static, bilingual landing page on GitHub Pages. Shaped like heartbank.ceo's build.
//
// ⭐⭐ IT IS STATIC ON PURPOSE, AND THE PURPOSE IS A PROPERTY. The landing takes no payment, holds no
//     account and writes nothing; the app is thank.heartbank.org. With no Firebase project and no
//     service worker, "the landing carries no app machinery" is not a rule anyone must remember.
//
// The pages sit at the REPOSITORY ROOT and are generated by scripts/pages.py from the drawing
// (../demo.heartbank.org). The estate's shared workflows find a page's source by that layout.

// ONE definition of the site's shape: the build inputs and the checks on static/sitemap.xml and
// snapshot-urls.txt are all derived from it. /login and 404.html are real documents but not pages
// anyone navigates to or a search engine should list, so they are outside NAV.
const NAV: { dir: string }[] = [{ dir: "" }, { dir: "km" }];
// Addresses that USED to be pages. GitHub Pages cannot send a 301 of its own, so each gets a generated
// forwarding document: an instant meta refresh (search engines treat it as permanent), a canonical link,
// and a script that carries the #fragment. ⛔ Never delete a row: a published address is cited somewhere.
const MOVED: { from: string; to: string }[] = [
    // The retired single-page app's About page.
    { from: "about", to: "" }
];

const urlOf = (dir: string) => (dir === "" ? "/" : `/${dir}/`);
const ORIGIN = "https://heartbank.org";
const ROOT = import.meta.dirname;

function siteShape(): Plugin {
    return {
        name: "site-shape",
        apply: "build",
        buildStart() {
            const want = NAV.map(({ dir }) => ORIGIN + urlOf(dir));
            const sitemap = readFileSync(join(ROOT, "static/sitemap.xml"), "utf8");
            const locs = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]);
            const missing = want.filter((u) => !locs.includes(u));
            const extra = locs.filter((u) => !want.includes(u));
            if (missing.length || extra.length)
                throw new Error(
                    `static/sitemap.xml disagrees with NAV — missing: ${missing.join(", ") || "none"}; not a page: ${extra.join(", ") || "none"}`
                );
            const manifest = readFileSync(join(ROOT, "snapshot-urls.txt"), "utf8").split("\n").map((l) => l.split("#")[0].trim());
            const unarchived = want.filter((u) => !manifest.includes(u));
            if (unarchived.length) throw new Error(`snapshot-urls.txt is missing ${unarchived.join(", ")}`);
            // ⛔ The kill switch must keep being served: the retired single-page app's worker is still installed
            //   in every browser that opened heartbank.org, and only this file can evict it.
            if (!existsSync(join(ROOT, "static/sw.js"))) throw new Error("static/sw.js is missing — the old service worker can never be evicted");
            const pages = ["index.html", "404.html", ...NAV.map(({ dir }) => join(dir, "index.html")), "login/index.html"];
            if (/navigator\.serviceWorker\.register/.test(pages.map((f) => readFileSync(join(ROOT, f), "utf8")).join("\n")))
                throw new Error("a page registers a service worker — this site must register none");
            // ⛔ every page carries hreflang pairs and an absolute og:image: a relative one fails silently.
            for (const f of ["index.html", "km/index.html"]) {
                const html = readFileSync(join(ROOT, f), "utf8");
                if (!/property="og:image" content="https:\/\//.test(html)) throw new Error(`${f}: og:image is missing or not absolute`);
                if (!/hreflang="x-default"/.test(html)) throw new Error(`${f}: hreflang pair is missing`);
            }
            this.info(`site shape: ${NAV.length} pages; sitemap and snapshot manifest agree with NAV`);
        },
        closeBundle() {
            for (const { from, to } of MOVED) {
                const dir = join(ROOT, "dist", from);
                mkdirSync(dir, { recursive: true });
                writeFileSync(
                    join(dir, "index.html"),
                    `<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8" />\n<title>Moved — HeartBank®</title>\n` +
                        `<link rel="canonical" href="${ORIGIN + urlOf(to)}" />\n<meta http-equiv="refresh" content="0; url=${urlOf(to)}" />\n` +
                        `<script>location.replace(${JSON.stringify(urlOf(to))} + location.hash)</script>\n</head>\n` +
                        `<body>\n<p>This page is now at <a href="${urlOf(to)}">${ORIGIN + urlOf(to)}</a>.</p>\n</body>\n</html>\n`
                );
            }
        }
    };
}

export default defineConfig({
    root: ROOT,
    publicDir: "static",
    appType: "mpa",
    plugins: [tailwindcss(), siteShape()],
    server: { port: 61284, host: true },
    preview: { port: 61284, host: true },
    build: {
        outDir: "dist",
        emptyOutDir: true,
        target: "es2021",
        rollupOptions: {
            input: {
                index: resolve(ROOT, "index.html"),
                km: resolve(ROOT, "km/index.html"),
                login: resolve(ROOT, "login/index.html"),
                "404": resolve(ROOT, "404.html")
            }
        }
    }
});
